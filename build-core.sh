#!/bin/sh
set -eu

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
if [ -x /opt/homebrew/opt/llvm/bin/clang ]; then
  CLANG=/opt/homebrew/opt/llvm/bin/clang
elif command -v clang >/dev/null 2>&1 && command -v wasm-ld >/dev/null 2>&1; then
  CLANG=$(command -v clang)
else
  echo "A clang toolchain with wasm-ld is required to rebuild the C core." >&2
  exit 1
fi

"$CLANG" --target=wasm32 -Oz -fno-builtin -nostdlib \
  -Wl,--no-entry -Wl,--allow-undefined -Wl,--export-all \
  -Wl,--export-memory -Wl,--initial-memory=131072 -Wl,--max-memory=131072 \
  -o "$ROOT/core.wasm" "$ROOT/src/core.c"

python3 - "$ROOT/core.wasm" "$ROOT/core-data.js" <<'PY'
import base64
import pathlib
import sys

source = pathlib.Path(sys.argv[1]).read_bytes()
pathlib.Path(sys.argv[2]).write_text(
    '// Generated by build-core.sh from src/core.c.\n'
    'window.N1_CORE_BASE64 = "' + base64.b64encode(source).decode('ascii') + '";\n',
    encoding='ascii',
)
PY

echo "C core: $(wc -c < "$ROOT/core.wasm" | tr -d ' ') bytes WebAssembly"
